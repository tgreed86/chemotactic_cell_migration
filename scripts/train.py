#!/usr/bin/env python3
"""Train configurable GNNs on chemotactic cell-migration trajectories.

This trainer follows the overall conventions of ``../1D_traffic/scripts/train.py``:
trajectory-disjoint train/validation/test splits, normalization learned only
from the training split, JSON configuration with command-line overrides,
early stopping, and a self-contained checkpoint.

The model input deliberately does *not* use a precomputed, state-dependent
advection operator. At every rollout step the core node features are density,
chemoattractant, cell area, and a boundary flag. The prescribed drift velocity
chi*grad(c), chemotactic sensitivity chi, absolute center coordinates, and four
distances to the rectangular domain boundaries are independently configurable.

All continuous channels are normalized with training-split statistics. The
static chemical field and mesh features (and chi, when included) stay fixed
within a trajectory; only density is replaced autoregressively. Stored mesh
edge attributes provide geometry to MeshGraphNet and FluxGraphNet. SAGEConv
uses graph connectivity and the node-level geometry.

``autoregressive_steps=1`` gives ordinary one-step training.  Values greater
than one unroll the model without teacher forcing: each predicted density is
fed to the next step and gradients propagate through the complete unroll.

Supported targets are:

* ``state``: predict n(t + dt)
* ``delta``: predict n(t + dt) - n(t)
* ``rate``:  predict (n(t + dt) - n(t)) / dt

For FluxGraphNet, ``node_weight_loss`` and ``flux_loss_weight`` control a
weighted sum of node-state rollout MSE and direct interface-transport MSE.
Flux targets must be present in archives generated by the current data
generator; setting ``flux_loss_weight=0`` preserves node-only training. Both
weight settings are ignored by SAGEConv and MeshGraphNet, which use the
standard unweighted node objective.

By default, FluxGraphNet's face decoder emits transport in physical units.
Setting ``decode_normalized_flux=true`` instead makes it emit a dimensionless
standardized value and applies ``flux_mean + flux_std * decoded_flux`` before
the conservative finite-volume update. The flux statistics are learned from
training trajectories only and are stored in the checkpoint.

FluxGraphNet decodes one signed transport per interior face and applies equal
and opposite mass changes to the adjacent finite-volume cells.  It therefore
conserves area-weighted mass by construction, including for ``state`` targets.

Example:

    python scripts/train.py --config config_chemotaxis_gnn.json

Explicit command-line values override the JSON config:

    python scripts/train.py --config config_chemotaxis_gnn.json \
        --model meshgraphnet --target-type rate --autoregressive-steps 8
"""

