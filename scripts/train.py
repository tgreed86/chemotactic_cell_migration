def load_config(path: Path, allowed_keys: Sequence[str]) -> Dict[str, object]:
    if not path.is_file():
        raise FileNotFoundError(f"Config file does not exist: {path}")
    with path.open("r", encoding="utf-8") as stream:
        config = json.load(stream)
    if not isinstance(config, dict):
        raise ValueError("The config file must contain one JSON object.")
    unknown = sorted(set(config) - set(allowed_keys))
    if unknown:
        raise ValueError(
            "Unknown config option(s): " + ", ".join(unknown)
        )
    return config


def parse_args(argv: Optional[Sequence[str]] = None) -> argparse.Namespace:
    parser = build_argument_parser()
    config_parser = argparse.ArgumentParser(add_help=False)
    config_parser.add_argument("--config", type=Path)
    config_args, _ = config_parser.parse_known_args(argv)
    if config_args.config is not None:
        allowed_keys = [
            action.dest
            for action in parser._actions
            if action.dest not in ("help", "config")
        ]
        parser.set_defaults(
            **load_config(config_args.config, allowed_keys)
        )
    args = parser.parse_args(argv)
    args.data = Path(args.data)
    args.output = Path(args.output)
    return args


def resolved_config(args: argparse.Namespace) -> Dict[str, object]:
    result: Dict[str, object] = {}
    for key, value in vars(args).items():
        if key == "config":
            continue
        result[key] = str(value) if isinstance(value, Path) else value
    return result


def validate_args(args: argparse.Namespace, *, max_steps: int) -> None:
    if args.epochs <= 0 or args.batch_size <= 0 or args.hidden_channels <= 0:
        raise ValueError("epochs, batch_size, and hidden_channels must be positive.")
    minimum_layers = 2 if args.model == "sageconv" else 1
    if args.num_layers < minimum_layers:
        raise ValueError(
            f"num_layers must be at least {minimum_layers} for {args.model}."
        )
    if args.autoregressive_steps <= 0 or args.autoregressive_steps > max_steps:
        raise ValueError(
            f"autoregressive_steps must be in [1, {max_steps}]."
        )
    if not (0.0 <= args.dropout < 1.0):
        raise ValueError("dropout must be in [0, 1).")
    if args.learning_rate <= 0.0 or args.weight_decay < 0.0:
        raise ValueError("learning_rate must be positive and weight_decay nonnegative.")
    if args.model == "fluxgraphnet":
        if args.node_weight_loss < 0.0 or args.flux_loss_weight < 0.0:
            raise ValueError(
                "node_weight_loss and flux_loss_weight must be nonnegative."
            )
        if args.node_weight_loss == 0.0 and args.flux_loss_weight == 0.0:
            raise ValueError(
                "At least one of node_weight_loss and flux_loss_weight must "
                "be positive."
            )
    elif args.decode_normalized_flux:
        raise ValueError(
            "decode_normalized_flux is supported only for FluxGraphNet."
        )
    if args.gradient_clip_norm < 0.0:
        raise ValueError("gradient_clip_norm must be nonnegative.")
    if args.patience < 0 or args.num_workers < 0 or args.log_every <= 0:
        raise ValueError("patience/num_workers must be nonnegative; log_every positive.")
    boolean_options = (
        "layer_norm",
        "include_chi",
        "include_drift_velocity",
        "include_absolute_positions",
        "include_boundary_distances",
        "mass_projection",
        "decode_normalized_flux",
    )
    invalid_booleans = [
        name for name in boolean_options if not isinstance(getattr(args, name), bool)
    ]
    if invalid_booleans:
        raise ValueError(
            "These configuration options must be booleans: "
            + ", ".join(invalid_booleans)
        )


def main(argv: Optional[Sequence[str]] = None) -> None:
    args = parse_args(argv)
    data = load_archive(args.data)
    max_steps = int(data["rollout_states"].shape[1] - 1)
    validate_args(args, max_steps=max_steps)
    if args.model == "fluxgraphnet":
        node_weight_loss = float(args.node_weight_loss)
        flux_loss_weight = float(args.flux_loss_weight)
    else:
        # These weights control FluxGraphNet's two-part supervised objective.
        # Other architectures retain their original, unweighted node loss.
        node_weight_loss = 1.0
        flux_loss_weight = 0.0
    set_seed(args.seed)
    device = choose_device(args.device)

    split_ids = split_trajectories(
        int(data["rollout_states"].shape[0]),
        train_fraction=args.train_fraction,
        validation_fraction=args.validation_fraction,
        test_fraction=args.test_fraction,
        seed=args.seed,
    )
    flux_targets = None
    flux_normalization = None
    needs_flux_normalization = (
        flux_loss_weight > 0.0
        or (args.model == "fluxgraphnet" and args.decode_normalized_flux)
    )
    if needs_flux_normalization:
        available_flux_targets = interface_flux_targets(data, args.target_type)
        flux_normalization = compute_flux_normalization(
            available_flux_targets, split_ids["train"]
        )
        if flux_loss_weight > 0.0:
            flux_targets = available_flux_targets
    normalization = compute_normalization(
        data,
        split_ids["train"],
        target_type=args.target_type,
        include_chi=args.include_chi,
        include_drift_velocity=args.include_drift_velocity,
        include_absolute_positions=args.include_absolute_positions,
        include_boundary_distances=args.include_boundary_distances,
    )
    static_node_features, edge_attr, undirected_edge_attr = prepare_features(
        data,
        normalization,
        include_chi=args.include_chi,
        include_drift_velocity=args.include_drift_velocity,
        include_absolute_positions=args.include_absolute_positions,
        include_boundary_distances=args.include_boundary_distances,
    )
    datasets = {
        name: ChemotaxisRolloutDataset(
            data=data,
            trajectory_ids=trajectory_ids,
            autoregressive_steps=args.autoregressive_steps,
            static_node_features=static_node_features,
            edge_attr=edge_attr,
            undirected_edge_attr=undirected_edge_attr,
            flux_targets=flux_targets,
        )
        for name, trajectory_ids in split_ids.items()
    }

    loader_generator = torch.Generator()
    loader_generator.manual_seed(args.seed)
    pin_memory = device.type == "cuda"
    loaders = {
        "train": make_loader(
            datasets["train"],
            batch_size=args.batch_size,
            shuffle=True,
            num_workers=args.num_workers,
            pin_memory=pin_memory,
            generator=loader_generator,
        ),
        "validation": make_loader(
            datasets["validation"],
            batch_size=args.batch_size,
            shuffle=False,
            num_workers=args.num_workers,
            pin_memory=pin_memory,
        ),
        "test": make_loader(
            datasets["test"],
            batch_size=args.batch_size,
            shuffle=False,
            num_workers=args.num_workers,
            pin_memory=pin_memory,
        ),
    }

    input_channels = 1 + int(static_node_features.shape[-1])
    edge_attr_channels = int(edge_attr.shape[-1])
    model, model_kwargs = build_model(
        args.model,
        in_channels=input_channels,
        edge_attr_channels=edge_attr_channels,
        hidden_channels=args.hidden_channels,
        num_layers=args.num_layers,
        dropout=args.dropout,
        layer_norm=args.layer_norm,
        target_type=args.target_type,
        normalization=normalization,
        decode_normalized_flux=args.decode_normalized_flux,
        flux_normalization=flux_normalization,
    )
    model = model.to(device)
    optimizer = AdamW(
        model.parameters(),
        lr=args.learning_rate,
        weight_decay=args.weight_decay,
    )

    args.output.mkdir(parents=True, exist_ok=True)
    effective_config = resolved_config(args)
    effective_config["node_weight_loss"] = node_weight_loss
    effective_config["flux_loss_weight"] = flux_loss_weight
    config_path = args.output / "config.json"
    checkpoint_path = args.output / "checkpoint.pt"
    history_path = args.output / "history.json"
    with config_path.open("w", encoding="utf-8") as stream:
        json.dump(effective_config, stream, indent=2, sort_keys=True)
        stream.write("\n")

    continuous_feature_names = static_continuous_feature_names(
        include_chi=args.include_chi,
        include_drift_velocity=args.include_drift_velocity,
        include_absolute_positions=args.include_absolute_positions,
        include_boundary_distances=args.include_boundary_distances,
    )
    feature_names = [
        "normalized_density",
        *[f"normalized_{name}" for name in continuous_feature_names],
        "boundary_cell",
    ]
    print(f"device: {device}")
    print(f"model: {args.model} ({type(model).__name__})")
    print(f"target_type: {args.target_type}")
    print(f"autoregressive_steps: {args.autoregressive_steps}")
    print(f"mass_projection: {args.mass_projection}")
    print(f"decode_normalized_flux: {args.decode_normalized_flux}")
    print(f"node_weight_loss: {node_weight_loss}")
    print(f"flux_loss_weight: {flux_loss_weight}")
    if args.model != "fluxgraphnet":
        print(
            "loss-weight config: ignored for this architecture; using the "
            "standard unweighted node objective"
        )
    if flux_normalization is not None:
        print(
            "flux target normalization: "
            f"mean={flux_normalization.mean:.8e}, "
            f"std={flux_normalization.std:.8e}"
        )
    print(
        "trajectories: "
        + ", ".join(f"{name}={ids.size}" for name, ids in split_ids.items())
    )
    print(
        "rollout windows: "
        + ", ".join(f"{name}={len(dataset)}" for name, dataset in datasets.items())
    )
    print(
        f"graph: nodes={data['rollout_states'].shape[2]}, "
        f"directed_edges={data['edge_index'].shape[2]}, "
        f"interior_faces={data['undirected_edge_index'].shape[2]}"
    )
    print("node inputs: " + ", ".join(feature_names))
    print("state-dependent physics-operator inputs: none")

    best_state: Optional[Dict[str, Tensor]] = None
    best_validation = float("inf")
    best_epoch = 0
    epochs_without_improvement = 0
    history: List[Dict[str, float]] = []

    for epoch in range(1, args.epochs + 1):
        start_time = time.perf_counter()
        train_metrics = train_epoch(
            model,
            loaders["train"],
            optimizer,
            device=device,
            normalization=normalization,
            target_type=args.target_type,
            autoregressive_steps=args.autoregressive_steps,
            mass_projection=args.mass_projection,
            gradient_clip_norm=args.gradient_clip_norm,
            node_weight_loss=node_weight_loss,
            flux_loss_weight=flux_loss_weight,
            flux_normalization=flux_normalization,
        )
        validation_metrics = evaluate(
            model,
            loaders["validation"],
            device=device,
            normalization=normalization,
            target_type=args.target_type,
            autoregressive_steps=args.autoregressive_steps,
            mass_projection=args.mass_projection,
            node_weight_loss=node_weight_loss,
            flux_loss_weight=flux_loss_weight,
            flux_normalization=flux_normalization,
        )
        entry: Dict[str, float] = {"epoch": float(epoch)}
        entry.update({f"train_{key}": value for key, value in train_metrics.items()})
        entry.update(
            {f"validation_{key}": value for key, value in validation_metrics.items()}
        )
        history.append(entry)

        improved = validation_metrics["normalized_mse"] < best_validation
        if improved:
            best_validation = validation_metrics["normalized_mse"]
            best_epoch = epoch
            best_state = copy.deepcopy(model.state_dict())
            epochs_without_improvement = 0
        else:
            epochs_without_improvement += 1

        if epoch == 1 or epoch % args.log_every == 0 or epoch == args.epochs:
            flux_text = (
                f" | train flux nMSE {train_metrics['flux_normalized_mse']:.6e}"
                f" | val flux nMSE {validation_metrics['flux_normalized_mse']:.6e}"
                if flux_loss_weight > 0.0
                else ""
            )
            print(
                f"epoch {epoch:04d} | "
                f"time {format_elapsed_time(time.perf_counter() - start_time)} | "
                f"train nMSE {train_metrics['normalized_mse']:.6e} | "
                f"val nMSE {validation_metrics['normalized_mse']:.6e} | "
                f"val state RMSE {validation_metrics['next_state_rmse']:.6e} | "
                f"val mass MAE {validation_metrics['mass_mae']:.6e}"
                f"{flux_text}"
            )
        if args.patience > 0 and epochs_without_improvement >= args.patience:
            print(
                f"early stopping at epoch {epoch}; best epoch was {best_epoch}"
            )
            break

    if best_state is None:
        raise RuntimeError("Training did not produce a checkpoint.")
    model.load_state_dict(best_state)
    test_metrics = evaluate(
        model,
        loaders["test"],
        device=device,
        normalization=normalization,
        target_type=args.target_type,
        autoregressive_steps=args.autoregressive_steps,
        mass_projection=args.mass_projection,
        node_weight_loss=node_weight_loss,
        flux_loss_weight=flux_loss_weight,
        flux_normalization=flux_normalization,
    )

    checkpoint = {
        "model_state_dict": {
            key: value.detach().cpu() for key, value in model.state_dict().items()
        },
        "model_class": type(model).__name__,
        "model_name": args.model,
        "model_kwargs": model_kwargs,
        "normalization": asdict(normalization),
        "feature_names": feature_names,
        "feature_options": {
            "include_chi": args.include_chi,
            "include_drift_velocity": args.include_drift_velocity,
            "include_absolute_positions": args.include_absolute_positions,
            "include_boundary_distances": args.include_boundary_distances,
        },
        "edge_attr_columns": str(data.get("edge_attr_columns", "")),
        "target_type": args.target_type,
        "autoregressive_steps": args.autoregressive_steps,
        "mass_projection": args.mass_projection,
        "node_weight_loss": node_weight_loss,
        "flux_loss_weight": flux_loss_weight,
        "flux_normalization": (
            asdict(flux_normalization) if flux_normalization is not None else None
        ),
        "dt": _scalar(data["dt"], "dt"),
        "diffusion": (
            _scalar(data["diffusion"], "diffusion")
            if "diffusion" in data
            else None
        ),
        "data_path": str(args.data),
        "training_args": effective_config,
        "source_config_path": str(args.config) if args.config else None,
        "split_trajectory_ids": {
            name: ids.tolist() for name, ids in split_ids.items()
        },
        "best_epoch": best_epoch,
        "best_validation_normalized_mse": best_validation,
        "test_metrics": test_metrics,
        "history": history,
    }
    torch.save(checkpoint, checkpoint_path)
    with history_path.open("w", encoding="utf-8") as stream:
        json.dump(history, stream, indent=2)
        stream.write("\n")

    print(f"best epoch: {best_epoch}")
    print("test metrics:")
    print(json.dumps(test_metrics, indent=2, sort_keys=True))
    print(f"saved checkpoint: {checkpoint_path}")
    print(f"saved config: {config_path}")
    print(f"saved history: {history_path}")


if __name__ == "__main__":
    main()
