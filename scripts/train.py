def format_elapsed_time(seconds: float) -> str:
    total = max(0, int(round(seconds)))
    hours, remainder = divmod(total, 3600)
    minutes, seconds = divmod(remainder, 60)
    return f"{hours:02d}:{minutes:02d}:{seconds:02d}"


def add_boolean_argument(
    parser: argparse.ArgumentParser, name: str, *, default: bool, help_text: str
) -> None:
    """Add --option/--no-option while retaining JSON-config compatibility."""
    destination = name.replace("-", "_")
    group = parser.add_mutually_exclusive_group()
    group.add_argument(
        f"--{name}", dest=destination, action="store_true", help=help_text
    )
    group.add_argument(
        f"--no-{name}", dest=destination, action="store_false"
    )
    parser.set_defaults(**{destination: default})


